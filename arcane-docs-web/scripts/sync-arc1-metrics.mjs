#!/usr/bin/env node
/**
 * Writes src/config/arc1-metrics.ts from ../Models/arc1_arc1_tiny.metrics.json
 * so the ARC 1 page always shows the numbers of the checked-in weights.
 *
 * Usage (from arcane-docs-web): node scripts/sync-arc1-metrics.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import crypto from "node:crypto";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const metricsPath = process.env.ARC1_METRICS_PATH || path.join(repoRoot, "Models", "arc1_arc1_tiny.metrics.json");
const configPath = process.env.ARC1_CONFIG_PATH || path.join(repoRoot, "Models", "arc1_arc1_tiny.config.json");
const outPath = path.join(here, "..", "src", "config", "arc1-metrics.ts");

const metrics = JSON.parse(fs.readFileSync(metricsPath, "utf8"));
const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
const evaluation = metrics.evaluation || {};
const keys = Object.keys(evaluation)
  .filter((k) => k.startsWith("cycles_"))
  .sort((a, b) => Number(a.split("_")[1]) - Number(b.split("_")[1]));
if (!keys.length) throw new Error(`No cycles_* evaluation in ${metricsPath}`);

const byCycles = keys.map((k) => {
  const e = evaluation[k];
  return {
    cycles: Number(k.split("_")[1]),
    toolSelection: e.tools_heldout_values.tool_selection_acc,
    exactCall: e.tools_heldout_values.exact_call_acc,
    argumentAcc: e.tools_heldout_values.argument_acc,
    noToolAcc: e.tools_heldout_values.no_tool_acc,
    exactCallUnseen: e.tools_unseen_tools.exact_call_acc,
    extractionF1: e.extraction_heldout_values.field_f1,
    classifyIntent: e.classify_heldout ? e.classify_heldout.accuracy_intent_domain : 0,
    classifySentiment: e.classify_heldout ? e.classify_heldout.accuracy_sentiment : 0,
    classifySupport: e.classify_heldout ? e.classify_heldout.accuracy_support : 0,
    classifyUnseen: e.classify_unseen_tools ? e.classify_unseen_tools.accuracy : 0,
    latencyP50Ms: e.tools_heldout_values.latency_ms_p50,
  };
});
const full = byCycles[byCycles.length - 1];

const benchPath = path.join(repoRoot, "Models", "arc1_rcn_benchmark.json");
const bench = JSON.parse(fs.readFileSync(benchPath, "utf8"));
const rcnFile = path.join(here, "..", "public", "models", "arc1-tiny.rcn");
const rcnBytes = fs.readFileSync(rcnFile);
const formats = [
  ["Keras weights, f32", bench["weights.h5 (f32)"]],
  [".rcn f16", bench.f16],
  ["TFLite int8", bench["tflite int8"]],
  [".rcn rq8", bench.rq8],
  [".rcn rq4", bench.rq4],
]
  .filter(([, v]) => v)
  .map(([label, v]) => ({ label, bytes: v.bytes, exactCall: v.exact_call ?? null, extractF1: v.extract_f1 ?? null }));

const data = {
  rcn: {
    file: "/models/arc1-tiny.rcn",
    bytes: rcnBytes.length,
    sha256: crypto.createHash("sha256").update(rcnBytes).digest("hex"),
    quant: "rq4",
  },
  formats,
  parameters: metrics.parameters,
  cycles: full.cycles,
  seqLen: config.seq_len,
  latencyP50Ms: full.latencyP50Ms,
  fireEceBefore: metrics.calibration.fire_ece_before,
  fireEceAfter: metrics.calibration.fire_ece_after,
  retrievalAt1: evaluation.embeddings ? evaluation.embeddings.intent_retrieval_at_1 : 0,
  byCycles,
};

const body = `// Generated by scripts/sync-arc1-metrics.mjs from Models/arc1_arc1_tiny.metrics.json. Do not edit.
export const ARC1_METRICS = ${JSON.stringify(data, null, 2)} as const;
`;
fs.writeFileSync(outPath, body);
console.log(`wrote ${path.relative(process.cwd(), outPath)}`);
